  static pw.Document _buildPdf(Map<String, dynamic> payslip, int year, int month, {String lang = 'en'}) {
    final pdf = pw.Document();
    final monthName = DateFormat('MMMM yyyy').format(DateTime(year, month));
    final s = _l(lang);

    // Extract data - All individual components
    final basicSalary = _n(payslip['basic_salary']);
    final transportAllowance = _n(payslip['transport_allowance']);
    final mealAllowance = _n(payslip['meal_allowance']);
    final phoneAllowance = _n(payslip['phone_allowance']);
    final housingAllowance = _n(payslip['housing_allowance']);
    final positionAllowance = _n(payslip['position_allowance']);
    final otherAllowance = _n(payslip['other_allowance']);
    final totalAllowances = _n(payslip['total_allowances']);
    final otHours = _n(payslip['ot_hours']);
    final otAmount = _n(payslip['ot_amount']);
    final attendanceBonus = _n(payslip['attendance_bonus']);
    final performanceBonus = _n(payslip['performance_bonus']);
    final incentive = _n(payslip['incentive']);
    final commission = _n(payslip['commission']);
    final bonus = _n(payslip['bonus']);
    final otherEarnings = _n(payslip['other_earnings']);
    final grossSalary = _n(payslip['gross_salary']);
    final ssbAmount = _n(payslip['ssb_amount']);
    final taxAmount = _n(payslip['tax_amount']);
    final advanceDeduction = _n(payslip['advance_deduction']);
    final absentDeduction = _n(payslip['absent_deduction']);
    final unpaidLeaveDeduction = _n(payslip['unpaid_leave_deduction']);
    final lateDeduction = _n(payslip['late_deduction']);
    final loanDeduction = _n(payslip['loan_deduction']);
    final insuranceDeduction = _n(payslip['insurance_deduction']);
    final uniformDeduction = _n(payslip['uniform_deduction']);
    final otherDeductions = _n(payslip['other_deductions']);
    final totalDeductions = _n(payslip['total_deductions']);
    final netSalary = _n(payslip['net_salary']);
    final daysPresent = payslip['days_present'] ?? 0;
    final daysAbsent = payslip['days_absent'] ?? 0;
    final daysLate = payslip['days_late'] ?? 0;
    final daysOnLeave = payslip['days_on_leave'] ?? 0;
    final totalWorkingDays = payslip['total_working_days'] ?? 0;
    final status = payslip['status'] ?? 'calculated';

    // Employee info
    final emp = payslip['employee'] is Map ? payslip['employee'] as Map : {};
    final empName = '${emp['first_name'] ?? ''} ${emp['last_name'] ?? ''}'.trim();
    final empNameMm = emp['name_mm'] ?? '';
    final empCode = emp['employee_code'] ?? '';
    final empPhone = emp['phone'] ?? '';
    final empNrc = emp['nrc_number'] ?? '';
    final empSsb = emp['ssb_number'] ?? '';
    final bankName = emp['bank_name'] ?? '';
    final bankAccount = emp['bank_account_number'] ?? '';
    final dept = emp['department'] is Map ? emp['department']['name'] ?? '' : '';
    final position = emp['position'] is Map ? emp['position']['title'] ?? '' : '';

    // Company info
    final company = emp['company'] is Map ? emp['company'] as Map : {};
    final companyName = company['name'] ?? 'Easy HR';
    final companyNameMm = company['name_mm'] ?? '';
    final companyAddress = company['address'] ?? '';
    final companyPhone = company['phone'] ?? '';
    final companyEmail = company['email'] ?? '';

    final accent = PdfColor.fromHex('#2563EB');
    final green = PdfColor.fromHex('#10B981');
    final red = PdfColor.fromHex('#EF4444');
    final lightBg = PdfColor.fromHex('#F8FAFC');
    final borderColor = PdfColor.fromHex('#E2E8F0');

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              // ═══════════ HEADER ═══════════
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.symmetric(horizontal: 20, vertical: 16),
                decoration: pw.BoxDecoration(
                  color: accent,
                  borderRadius: pw.BorderRadius.circular(8),
                ),
                child: pw.Row(
                  children: [
                    pw.Expanded(
                      child: pw.Column(
                        crossAxisAlignment: pw.CrossAxisAlignment.start,
                        children: [
                          pw.Text(companyName.toString(),
                              style: pw.TextStyle(color: PdfColors.white, fontSize: 18, fontWeight: pw.FontWeight.bold)),
                          if (companyNameMm.toString().isNotEmpty)
                            pw.Text(companyNameMm.toString(), style: const pw.TextStyle(color: PdfColors.white, fontSize: 10)),
                          if (companyAddress.toString().isNotEmpty)
                            pw.Text(companyAddress.toString(), style: const pw.TextStyle(color: PdfColors.white, fontSize: 9)),
                          if (companyPhone.toString().isNotEmpty || companyEmail.toString().isNotEmpty)
                            pw.Text('${companyPhone.toString().isNotEmpty ? companyPhone : ''}${companyEmail.toString().isNotEmpty ? ' | $companyEmail' : ''}',
                                style: const pw.TextStyle(color: PdfColors.white, fontSize: 9)),
                        ],
                      ),
                    ),
                    pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.end,
                      children: [
                        pw.Text(s['payslip']!, style: pw.TextStyle(color: PdfColors.white, fontSize: 22, fontWeight: pw.FontWeight.bold)),
                        pw.SizedBox(height: 4),
                        pw.Container(
                          padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                          decoration: pw.BoxDecoration(
                            color: PdfColors.white,
                            borderRadius: pw.BorderRadius.circular(4),
                          ),
                          child: pw.Text(monthName, style: pw.TextStyle(color: accent, fontSize: 11, fontWeight: pw.FontWeight.bold)),
                        ),
                      ],
                    ),
                  ],
                ),
              ),
              pw.SizedBox(height: 16),

              // ═══════════ EMPLOYEE INFO + PAYROLL INFO ═══════════
              pw.Container(
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(color: borderColor),
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Row(
                  children: [
                    pw.Expanded(
                      child: pw.Container(
                        padding: const pw.EdgeInsets.all(12),
                        child: pw.Column(
                          crossAxisAlignment: pw.CrossAxisAlignment.start,
                          children: [
                            pw.Container(
                              padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                              color: lightBg,
                              child: pw.Text(s['employee_info']!, style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: accent)),
                            ),
                            pw.SizedBox(height: 6),
                            _infoRow(s['name']!, empNameMm.toString().isNotEmpty ? '$empName ($empNameMm)' : (empName.isEmpty ? 'N/A' : empName)),
                            _infoRow(s['emp_code']!, empCode.toString().isEmpty ? '-' : empCode.toString()),
                            _infoRow(s['department']!, dept.toString().isEmpty ? '-' : dept.toString()),
                            _infoRow(s['position']!, position.toString().isEmpty ? '-' : position.toString()),
                            _infoRow(s['phone']!, empPhone.toString().isEmpty ? '-' : empPhone.toString()),
                          ],
                        ),
                      ),
                    ),
                    pw.Container(width: 1, height: 110, color: borderColor),
                    pw.Expanded(
                      child: pw.Container(
                        padding: const pw.EdgeInsets.all(12),
                        child: pw.Column(
                          crossAxisAlignment: pw.CrossAxisAlignment.start,
                          children: [
                            pw.Container(
                              padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                              color: lightBg,
                              child: pw.Text(s['payroll_info']!, style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: accent)),
                            ),
                            pw.SizedBox(height: 6),
                            _infoRow(s['pay_period']!, monthName),
                            _infoRow(s['basic_salary']!, _fmt(basicSalary)),
                            _infoRow(s['nrc']!, empNrc.toString().isEmpty ? '-' : empNrc.toString()),
                            _infoRow(s['bank']!, bankName.toString().isEmpty ? '-' : bankName.toString()),
                            _infoRow(s['bank_acc']!, bankAccount.toString().isEmpty ? '-' : bankAccount.toString()),
                          ],
                        ),
                      ),
                    ),
                  ],
                ),
              ),
              pw.SizedBox(height: 12),

              // ═══════════ ATTENDANCE SUMMARY ═══════════
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.symmetric(vertical: 8, horizontal: 12),
                decoration: pw.BoxDecoration(
                  color: lightBg,
                  border: pw.Border.all(color: borderColor),
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
                  children: [
                    _attendanceItem(s['working_days']!, '$totalWorkingDays', accent),
                    _attendanceItem(s['present']!, '$daysPresent', green),
                    _attendanceItem(s['absent']!, '$daysAbsent', red),
                    _attendanceItem(s['late']!, '$daysLate', PdfColor.fromHex('#F59E0B')),
                    _attendanceItem(s['on_leave']!, '$daysOnLeave', PdfColor.fromHex('#8B5CF6')),
                  ],
                ),
              ),
              pw.SizedBox(height: 14),

              // ═══════════ EARNINGS TABLE ═══════════
              _sectionHeader(s['earnings']!, s['description']!, s['amount']!, green),
              _earningRow(s['basic_salary']!, basicSalary),
              if (transportAllowance > 0) _earningRow(s['transport']!, transportAllowance),
              if (mealAllowance > 0) _earningRow(s['meal']!, mealAllowance),
              if (phoneAllowance > 0) _earningRow(s['phone_allowance']!, phoneAllowance),
              if (housingAllowance > 0) _earningRow(s['housing']!, housingAllowance),
              if (positionAllowance > 0) _earningRow(s['position_allowance']!, positionAllowance),
              if (otherAllowance > 0) _earningRow(s['other_allowance']!, otherAllowance),
              if (totalAllowances > 0 && transportAllowance == 0 && mealAllowance == 0)
                _earningRow(lang == 'mm' ? 'စုစုပေါင်းစရိတ်' : 'Total Allowances', totalAllowances),
              if (attendanceBonus > 0) _earningRow(s['attendance_bonus']!, attendanceBonus),
              if (otAmount > 0) _earningRow('${s['overtime']!} (${otHours.toStringAsFixed(1)}h)', otAmount),
              if (performanceBonus > 0) _earningRow(s['performance_bonus']!, performanceBonus),
              if (incentive > 0) _earningRow(s['incentive']!, incentive),
              if (commission > 0) _earningRow(s['commission']!, commission),
              if (bonus > 0) _earningRow(payslip['bonus_description']?.toString().isNotEmpty == true ? payslip['bonus_description'].toString() : s['bonus']!, bonus),
              if (otherEarnings > 0) _earningRow(payslip['other_earnings_description']?.toString().isNotEmpty == true ? payslip['other_earnings_description'].toString() : s['other_earnings']!, otherEarnings),
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 6),
                color: PdfColor.fromHex('#ECFDF5'),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(s['total_earnings']!, style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: green)),
                    pw.Text(_fmt(grossSalary), style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: green)),
                  ],
                ),
              ),
              pw.SizedBox(height: 10),

              // ═══════════ DEDUCTIONS TABLE ═══════════
              _sectionHeader(s['deductions']!, s['description']!, s['amount']!, red),
              if (ssbAmount > 0) _earningRow(s['ssb']!, ssbAmount),
              if (taxAmount > 0) _earningRow(s['income_tax']!, taxAmount),
              if (advanceDeduction > 0) _earningRow(s['advance']!, advanceDeduction),
              if (absentDeduction > 0) _earningRow(s['absent_ded']!, absentDeduction),
              if (unpaidLeaveDeduction > 0) _earningRow(s['unpaid_leave_ded']!, unpaidLeaveDeduction),
              if (lateDeduction > 0) _earningRow(s['late_ded']!, lateDeduction),
              if (loanDeduction > 0) _earningRow(s['loan_ded']!, loanDeduction),
              if (insuranceDeduction > 0) _earningRow(s['insurance_ded']!, insuranceDeduction),
              if (uniformDeduction > 0) _earningRow(s['uniform_ded']!, uniformDeduction),
              if (otherDeductions > 0) _earningRow(payslip['other_deductions_description']?.toString().isNotEmpty == true ? payslip['other_deductions_description'].toString() : s['other_deductions']!, otherDeductions),
              if (totalDeductions == 0) _earningRow('-', 0),
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 6),
                color: PdfColor.fromHex('#FEF2F2'),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(s['total_deductions']!, style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: red)),
                    pw.Text(_fmt(totalDeductions), style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: red)),
                  ],
                ),
              ),
              pw.SizedBox(height: 14),

              // ═══════════ NET SALARY ═══════════
              pw.Container(
                width: double.infinity,
                padding: const pw.EdgeInsets.all(14),
                decoration: pw.BoxDecoration(
                  color: accent,
                  borderRadius: pw.BorderRadius.circular(8),
                ),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text('${s['net_salary']!} / ${lang == 'mm' ? 'လက်ခံရရှိငွေ' : 'Take Home'}',
                        style: pw.TextStyle(color: PdfColors.white, fontSize: 13, fontWeight: pw.FontWeight.bold)),
                    pw.Text(_fmt(netSalary),
                        style: pw.TextStyle(color: PdfColors.white, fontSize: 18, fontWeight: pw.FontWeight.bold)),
                  ],
                ),
              ),
              pw.Spacer(),

              // ═══════════ FOOTER ═══════════
              pw.Divider(color: borderColor),
              pw.SizedBox(height: 6),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(s['generated_by']!, style: const pw.TextStyle(color: PdfColors.grey, fontSize: 8)),
                  pw.Text('${s['date']!}: ${DateFormat('dd MMM yyyy').format(DateTime.now())}', style: const pw.TextStyle(color: PdfColors.grey, fontSize: 8)),
                ],
              ),
              pw.SizedBox(height: 3),
              pw.Text(s['confidential']!, style: const pw.TextStyle(color: PdfColors.grey, fontSize: 7)),
            ],
          );
        },
      ),
    );

    return pdf;
  }

  static double _n(dynamic v) => v == null ? 0.0 : (v as num).toDouble();

  static pw.Widget _sectionHeader(String title, String descLabel, String amountLabel, PdfColor color) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 6),
      color: color,
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(title, style: pw.TextStyle(color: PdfColors.white, fontSize: 10, fontWeight: pw.FontWeight.bold)),
          pw.Row(children: [
            pw.SizedBox(width: 80, child: pw.Text(descLabel, style: const pw.TextStyle(color: PdfColors.white, fontSize: 9), textAlign: pw.TextAlign.right)),
            pw.SizedBox(width: 10),
            pw.SizedBox(width: 80, child: pw.Text(amountLabel, style: const pw.TextStyle(color: PdfColors.white, fontSize: 9), textAlign: pw.TextAlign.right)),
          ]),
        ],
      ),
    );
  }

  static pw.Widget _earningRow(String label, double amount) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 5),
      decoration: const pw.BoxDecoration(
        border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey200, width: 0.5)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Expanded(child: pw.Text(label, style: const pw.TextStyle(fontSize: 9))),
          pw.Text(amount > 0 ? _fmt(amount) : '-', style: pw.TextStyle(fontSize: 9, fontWeight: amount > 0 ? pw.FontWeight.bold : pw.FontWeight.normal)),
        ],
      ),
    );
  }

  static pw.Widget _infoRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 3),
      child: pw.Row(
        children: [
