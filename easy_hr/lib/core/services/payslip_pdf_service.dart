  static Future<void> generateAndPreview(Map<String, dynamic> payslip, int year, int month, {String lang = 'en'}) async {
    final pdf = _buildPdf(payslip, year, month, lang: lang);
    await Printing.layoutPdf(onLayout: (format) => pdf.save());
  }

  static Future<void> sharePdf(Map<String, dynamic> payslip, int year, int month, {String lang = 'en'}) async {
    final pdf = _buildPdf(payslip, year, month, lang: lang);
    final bytes = await pdf.save();
    final monthName = DateFormat('MMMM_yyyy').format(DateTime(year, month));
    await Printing.sharePdf(bytes: bytes, filename: 'Payslip_$monthName.pdf');
  }

